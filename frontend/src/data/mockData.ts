// Summary metrics calculation
export function computeDashboardSummary(projects: Project[] = MOCK_PROJECTS): DashboardSummary {
  const total = projects.length;
  const highRisk = projects.filter(p => p.risk?.level === 'HIGH' || p.risk?.level === 'CRITICAL').length;
  const criticalRisk = projects.filter(p => p.risk?.level === 'CRITICAL').length;
  const onSchedule = projects.filter(p => p.status === 'ACTIVE' && p.risk?.score < 46).length;
  const needingAttention = projects.filter(p => p.needsAttention || p.risk?.score >= 70).length;
  const delayed = projects.filter(p => p.status === 'DELAYED').length;
  const environmentalAlerts = projects.reduce((sum, p) => sum + (p.environmentalFactors || []).filter(e => e.sensitivityLevel === 'HIGH' || e.sensitivityLevel === 'CRITICAL').length, 0);
  const legalAlerts = projects.reduce((sum, p) => sum + (p.legalIssues || []).filter(l => l.status === 'STAY_ORDER_ACTIVE').length, 0);
  const totalLandRequired = projects.reduce((sum, p) => sum + (p.landRequiredAcres || 0), 0);
  const totalLandAcquired = projects.reduce((sum, p) => sum + (p.landAcquiredAcres || 0), 0);
  const avgAcquisition = total > 0 ? Math.round(projects.reduce((sum, p) => sum + (p.acquisitionProgressPct || 0), 0) / total) : 0;
  const avgDelay = total > 0 ? Math.round(projects.reduce((sum, p) => sum + (p.risk?.estimatedDelayMonths || 0), 0) / total) : 0;
  const totalCompensationDisbursedPct = total > 0 ? Math.round(projects.reduce((sum, p) => sum + (p.compensation?.disbursedPct || 0), 0) / total) : 0;
  const totalLitigationCount = projects.reduce((sum, p) => sum + (p.legalIssues?.length || 0), 0);

  return {
    totalProjects: total,
    projectsOnSchedule: onSchedule,
    projectsNeedingAttention: needingAttention,
    highRiskProjects: highRisk,
    criticalRiskProjects: criticalRisk,
    delayedProjects: delayed,
    environmentalAlerts: environmentalAlerts,
    legalAlerts: legalAlerts,
    totalLandRequiredAcres: totalLandRequired,
    totalLandAcquiredAcres: totalLandAcquired,
    avgAcquisitionPct: avgAcquisition,
    avgDelayMonths: avgDelay,
    totalCompensationDisbursedPct,
    totalLitigationCount,
  };
}

